-- 商家注销账号申请表
CREATE TABLE IF NOT EXISTS `T_SELLER_DESTROY_APPLY` (
  `UUID`          VARCHAR(32)  NOT NULL COMMENT '主键',
  `SELLER_ID`     VARCHAR(32)  DEFAULT NULL COMMENT '申请商家 partyId(=Seller.UUID)',
  `ACCOUNT`       VARCHAR(64)  DEFAULT NULL COMMENT '申请时确认的账号(SecUser.username)',
  `APPLY_REASON`  VARCHAR(500) DEFAULT NULL COMMENT '申请原因',
  `STATUS`        INT          DEFAULT 0    COMMENT '0待审核 1已通过 2已拒绝',
  `APPLY_TIME`    DATETIME     DEFAULT NULL COMMENT '申请时间',
  `REVIEW_TIME`   DATETIME     DEFAULT NULL COMMENT '审核时间',
  `REVIEW_REMARK` VARCHAR(500) DEFAULT NULL COMMENT '审核备注/拒绝原因',
  `REVIEWER_NAME` VARCHAR(64)  DEFAULT NULL COMMENT '审核人(后台登录账号)',
  PRIMARY KEY (`UUID`),
  KEY `IDX_SDA_SELLER` (`SELLER_ID`),
  KEY `IDX_SDA_STATUS` (`STATUS`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='商家注销账号申请';
